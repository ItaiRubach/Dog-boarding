// Saves a lesson in the real app, then opens Yuval's own calendar link.
import { chromium } from 'playwright-core';
const [url, out] = process.argv.slice(2);
const b = await chromium.launch({ channel: 'msedge' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
const errors = [];
p.on('pageerror', (e) => errors.push(e.message));
await p.goto(url);
await p.getByLabel('הגדרות').click();
await p.getByText('גיבוי, שחזור ונתוני דוגמה').click();
await p.getByText('טען נתוני דוגמה').click();
await p.getByText('כן, החלף הכל בדוגמה').click();
await p.waitForTimeout(800);
await p.goto(url);
await p.getByText('+ אילוף').click();
await p.locator('#dp-search').fill('טופ');
await p.getByText(/^טופי/).first().click();
await p.getByRole('button', { name: 'שמור' }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/14-lesson-invite.png` });
const href = await p.getByText('הוסף ליומן שלי').getAttribute('href');
const page2 = await ctx.newPage();
page2.on('pageerror', (e) => errors.push(e.message));
await page2.goto(href.replace(/^https?:\/\/[^/]+\//, url));
await page2.waitForTimeout(300);
await page2.screenshot({ path: `${out}/15-lesson-calendar.png` });
const ics = decodeURIComponent((await page2.getAttribute('#apple', 'href')).split(',')[1]);
console.log(ics.match(/SUMMARY:[^\r]+|TRIGGER:[^\r]+|LOCATION:[^\r]+/g).join(' | '));
console.log('errors:', errors.length ? errors.join('\n') : 'none');
await b.close();
