import { chromium } from 'playwright-core';
const [url, out] = process.argv.slice(2);
const b = await chromium.launch({ channel: 'msedge' });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errors = [];
p.on('pageerror', (e) => errors.push(e.message));
await p.goto(url);
await p.getByLabel('הגדרות').click();
await p.getByText('גיבוי, שחזור ונתוני דוגמה').click();
await p.getByText('טען נתוני דוגמה').click();
await p.getByText('כן, החלף הכל בדוגמה').click();
await p.waitForTimeout(800);
await p.goto(url);
await p.getByText('+ אילוף').click();
await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/12-training-pick.png` });
await p.locator('#dp-search').fill('טופ');
await p.getByText(/^טופי/).first().click();
await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/13-training.png` });
console.log('errors:', errors.length ? errors.join('\n') : 'none');
await b.close();
