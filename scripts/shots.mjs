// Screenshots at iPhone size with the installed Edge. Usage: node scripts/shots.mjs <url> <outdir>
import { chromium } from 'playwright-core';
const [url, out] = process.argv.slice(2);
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'he-IL' });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
const shot = async (name) => { await page.waitForTimeout(250); await page.screenshot({ path: `${out}/${name}.png` }); };
await page.goto(url);
await page.getByText('ההגדרות', { exact: false }).count();
// load demo data
await page.getByLabel('הגדרות').click();
await page.getByText('גיבוי, שחזור ונתוני דוגמה').click();
await page.getByText('טען נתוני דוגמה').click();
await page.getByText('כן, החלף הכל בדוגמה').click();
await page.getByText('‹ חזרה').click();
await page.getByText('‹ חזרה').click();
await shot('1-home');
await page.getByRole('button', { name: /צהריים/ }).click();
await shot('2-home-noon');
await page.locator('.tok').first().click();
await shot('3-dog-sheet');
await page.locator('.scrim').click({ position: { x: 10, y: 10 } });
await page.getByText('יש מקום?').click();
await shot('4-avail');
await page.getByText(/^קבע ב/).click();
await shot('5-pick-dog');
await page.goto(url);
await page.getByRole('button', { name: /לוח/ }).click();
await shot('6-board');
await page.getByRole('button', { name: /כלבים/ }).click();
await page.getByText(/^טופי/).first().click();
await shot('7-dog-file');
await page.goto(url);
await page.getByText(/אילוף · ג׳ינג׳ר/).click();
await shot('8-training');
await page.goto(url);
await page.getByLabel('הגדרות').click();
await page.getByText('מפת התאים').click();
await shot('9-plan-editor');
await page.emulateMedia({ colorScheme: 'dark' });
await page.goto(url);
await shot('10-home-dark');
console.log('errors:', errors.length ? errors.join('\n') : 'none');
await browser.close();
